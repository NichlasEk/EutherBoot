#!/usr/bin/env python3
"""Render vendored SVGs to 64x64 alpha masks; no network or runtime SVG parser."""
import io,json,subprocess
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parent.parent
ASSETS=ROOT/'crates/uefi-app/assets/icons'

def luminance(rgb):
    linear=[v/255/12.92 if v/255 <= .04045 else ((v/255+.055)/1.055)**2.4 for v in rgb]
    return sum(a*b for a,b in zip(linear,(.2126,.7152,.0722)))

def contrast_color(rgb,bg,toward):
    for amount in range(256):
        color=tuple(round(v+(toward-v)*amount/255) for v in rgb)
        a,b=sorted((luminance(color),luminance(bg)))
        if (b+.05)/(a+.05)>=3: return color
    raise ValueError('No contrasting color')

manifest=json.loads((ASSETS/'manifest.json').read_text())
lines=['// Generated by scripts/build-os-icons.py from vendored SVGs.',"pub struct Icon {\n    pub alpha: &'static [u8; 4096],\n    pub dark: [u8; 3],\n    pub light: [u8; 3],\n}", 'pub fn asset(slug: &str) -> Option<Icon> {\n    Some(match slug {']
preview=Image.new('RGB',(800,((len(manifest['icons'])+7)//8)*110),(16,27,41))
draw=ImageDraw.Draw(preview)
font=ImageFont.load_default(size=10)
for i,icon in enumerate(manifest['icons']):
    slug=icon['slug'];svg=ASSETS/'svg'/f'{slug}.svg'
    png=subprocess.check_output(['rsvg-convert','-w','216','-h','216',str(svg)])
    small=Image.open(io.BytesIO(png)).convert('RGBA').resize((54,54),Image.Resampling.LANCZOS)
    alpha=Image.new('L',(64,64));alpha.paste(small.getchannel('A'),(5,5))
    (ASSETS/f'{slug}.alpha').write_bytes(alpha.tobytes())
    rgb=tuple(bytes.fromhex(icon['hex']))
    dark=contrast_color(rgb,(24,35,49),255);light=contrast_color(rgb,(247,246,241),0)
    lines.append(f'        "{slug}" => Icon {{\n            alpha: include_bytes!("../assets/icons/{slug}.alpha"),\n            dark: {list(dark)},\n            light: {list(light)},\n        }},')
    x=(i%8)*100;y=(i//8)*110
    preview.paste(Image.new('RGB',(64,64),dark),(x+18,y+8),alpha)
    draw.text((x+50,y+80),icon['name'],font=font,fill=(238,229,205),anchor='mt')
lines+=['        _ => return None,','    })','}']
(ROOT/'crates/uefi-app/src/os_icons.rs').write_text('\n'.join(lines)+'\n')
out=ROOT/'artifacts/icons';out.mkdir(parents=True,exist_ok=True)
preview.save(out/'icon-sheet.png')
print('Rendered',len(manifest['icons']),'64x64 alpha masks')
